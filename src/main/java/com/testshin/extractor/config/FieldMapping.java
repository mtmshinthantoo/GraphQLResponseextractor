package com.testshin.extractor.config;

public class FieldMapping {

    private String column;
    private String path;

    public FieldMapping() {
    }

    public String getColumn() {
        return column;
    }

    public void setColumn(String column) {
        this.column = column;
    }

    public String getPath() {
        return path;
    }

    public void setPath(String path) {
        this.path = path;
    }
}
